CREATE TABLE IF NOT EXISTS users (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 full_name VARCHAR(120) NOT NULL, dob VARCHAR(10) NOT NULL, phone VARCHAR(30) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(20) NOT NULL DEFAULT 'customer', verified_at DATETIME NULL,
 delivery_address TEXT NULL, session_version INTEGER NOT NULL DEFAULT 0, created_at DATETIME NOT NULL
);
CREATE TABLE IF NOT EXISTS tokens (
 id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(id), purpose VARCHAR(20) NOT NULL,
 token_hash VARCHAR(64) NOT NULL UNIQUE, expires_at DATETIME NOT NULL, created_at DATETIME NOT NULL
);
CREATE TABLE IF NOT EXISTS categories (
 id INTEGER PRIMARY KEY AUTOINCREMENT, name VARCHAR(80) NOT NULL UNIQUE, icon VARCHAR(16) NOT NULL DEFAULT '🍽️', active INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS files (
 id VARCHAR(48) PRIMARY KEY, owner_id INTEGER NOT NULL REFERENCES users(id), kind VARCHAR(20) NOT NULL,
 path VARCHAR(100) NOT NULL, mime VARCHAR(40) NOT NULL, created_at DATETIME NOT NULL
);
CREATE TABLE IF NOT EXISTS seller_applications (
 id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL UNIQUE REFERENCES users(id),
 business_name VARCHAR(120) NOT NULL, address TEXT NOT NULL, business_phone VARCHAR(30) NOT NULL,
 logo_id VARCHAR(48) NOT NULL REFERENCES files(id), cnic_encrypted TEXT NOT NULL,
 cnic_front VARCHAR(48) NOT NULL REFERENCES files(id), cnic_back VARCHAR(48) NOT NULL REFERENCES files(id),
 status VARCHAR(20) NOT NULL DEFAULT 'pending', review_note TEXT NULL, reviewed_by INTEGER NULL REFERENCES users(id),
 reviewed_at DATETIME NULL, submitted_at DATETIME NOT NULL
);
CREATE TABLE IF NOT EXISTS menu_items (
 id INTEGER PRIMARY KEY AUTOINCREMENT, seller_id INTEGER NOT NULL REFERENCES users(id), category_id INTEGER NOT NULL REFERENCES categories(id),
 photo_id VARCHAR(48) NOT NULL REFERENCES files(id), name VARCHAR(120) NOT NULL, description TEXT NOT NULL,
 ingredients TEXT NOT NULL, price_paisa INTEGER NOT NULL, expires_at DATETIME NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'published', created_at DATETIME NOT NULL, updated_at DATETIME NOT NULL
);
CREATE INDEX IF NOT EXISTS menu_expiry ON menu_items (status, expires_at);
CREATE TABLE IF NOT EXISTS outbox (
 id INTEGER PRIMARY KEY AUTOINCREMENT, recipient VARCHAR(254) NOT NULL, subject VARCHAR(200) NOT NULL,
 body TEXT NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'pending', created_at DATETIME NOT NULL
);
CREATE TABLE IF NOT EXISTS attempts (id INTEGER PRIMARY KEY AUTOINCREMENT, rate_key VARCHAR(64) NOT NULL, created_at DATETIME NOT NULL);
CREATE INDEX IF NOT EXISTS attempt_lookup ON attempts (rate_key, created_at);
CREATE TABLE IF NOT EXISTS audit_logs (
 id INTEGER PRIMARY KEY AUTOINCREMENT, admin_id INTEGER NOT NULL REFERENCES users(id), action VARCHAR(200) NOT NULL,
 target_id INTEGER NOT NULL, created_at DATETIME NOT NULL
);
